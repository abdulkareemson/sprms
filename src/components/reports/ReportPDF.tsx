// ─── Master Export Function ───────────────────────────────────────────────────

export async function generateReportPDF(params: ReportPDFParams) {
  // Load logo once — shared across all report types
  const logoB64 = await loadLogoBase64();

  switch (params.reportType) {
    case "patients":
      return generatePatientReportPDF(params, logoB64);
    case "appointments":
      return generateAppointmentReportPDF(params, logoB64);
    case "revenue":
      return generateRevenueReportPDF(params, logoB64);
    case "records":
      return generateRecordsReportPDF(params, logoB64);
    default:
      return generatePatientReportPDF(params, logoB64);
  }
}