// ─── Master Export Function ───────────────────────────────────────────────────

export function generateReportPDF(params: ReportPDFParams) {
  switch (params.reportType) {
    case "patients":
      return generatePatientReportPDF(params);
    case "appointments":
      return generateAppointmentReportPDF(params);
    case "revenue":
      return generateRevenueReportPDF(params);
    case "records":
      return generateRecordsReportPDF(params);
    default:
      return generatePatientReportPDF(params);
  }
}
